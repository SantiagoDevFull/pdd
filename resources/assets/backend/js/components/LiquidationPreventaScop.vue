<template>
    <!--begin::Modal-->
    <div class="modal fade" id="modal_scop" tabindex="-1" role="dialog" aria-labelledby="exampleModalLabel"
        aria-hidden="true">
        <div class="modal-dialog modal-dialog-centered modal-lg" role="document">
            <div class="modal-content">
                <!--begin::Form-->
                <form class="kt-form" @submit.prevent="formController(url_update, $event)">
                    <div class="modal-header">
                        <h5 class="modal-title" id="exampleModalLabel">Actualizar Scop</h5>
                        <button type="button" class="close" data-dismiss="modal" aria-label="Close">
                        </button>
                    </div>
                    <div class="modal-body">
                        <div class="kt-portlet__body">
                            <div class="row">
                                <input type="hidden" name="id" id="id" v-model="model.id">
                                <div class="col-lg-4">
                                    <div class="form-group">
                                        <label class="form-control-label">Scop:</label>
                                        <input type="text" class="form-control" name="scop_number" id="scop_number"
                                            placeholder="123456789" v-model="model.scop_number"
                                            @focus="$parent.clearErrorMsg($event)">
                                        <div id="scop_number-error" class="error invalid-feedback"></div>
                                    </div>
                                </div>
                            </div>
                        </div>
                    </div>
                    <div class="modal-footer">
                        <button type="submit" class="btn btn-success"> Actualizar </button>
                        <button type="button" class="btn btn-secondary" data-dismiss="modal">Cerrar</button>
                    </div>
                </form>
                <!--end::Form-->
            </div>
        </div>
    </div>
    <!--end::Modal-->
</template>

<script>
import EventBus from '../event-bus';

export default {
    props: {
        url_update: {
            type: String,
            default: ''
        },
    },
    data() {
        return {
            model: {
                id: '',
                scop_number: '',
            },
        }
    },
    watch: {


    },
    computed: {

    },
    created() {
        EventBus.$on('show_asign_scop', function (model) {

            EventBus.$emit('clear_modal');
            this.model = model;
            $('#modal_scop').modal('show');
        }.bind(this));

        EventBus.$on('clear_modal', function () {
            this.title = '';
            this.model.id = '';
            this.model.scop_number = '';
        }.bind(this));
    },
    mounted() {

    },
    methods: {

        formController: function (url_update, event) {
            var vm = this;

            var target = $(event.target);
            var url = url_update;
            var fd = new FormData(event.target);

            EventBus.$emit('loading', true);

            axios.post(url, fd, {
                headers: {
                    'Content-type': 'application/x-www-form-urlencoded',
                }
            }).then(response => {
                EventBus.$emit('loading', false);

                this.$parent.alertMsg(response.data);

                $('#modal_scop').modal('hide');
                EventBus.$emit('clear_modal');
                EventBus.$emit('refresh_table');

            }).catch(error => {
                EventBus.$emit('loading', false);
                console.log(error.response);
                var obj = error.response.data.errors;
                $('.modal').animate({
                    scrollTop: 0
                }, 500, 'swing');
                $.each(obj, function (i, item) {
                    let c_target = target.find("#" + i + "-error");
                    if (!c_target.attr('data-required')) {
                        let p = c_target.prev();
                        p.addClass('is-invalid');
                    } else {
                        c_target.css('display', 'block');
                    }
                    c_target.html(item);
                });
            });
        },
    }
};
</script>